#!/usr/bin/env python3
"""Generate packages/sdk/src/generated/errors.ts from programs/pump-hooks/src/errors.rs.

Anchor numbers `#[error_code]` variants from 6000 in declaration order.
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
src = (ROOT / "programs/pump-hooks/src/errors.rs").read_text()
body = src[src.index("pub enum PumpHooksError") :]
body = body[body.index("{") + 1 : body.index("\n}")]

rows, msg = [], None
for line in body.splitlines():
    line = line.strip()
    m = re.match(r'#\[msg\("(.*)"\)\]', line)
    if m:
        msg = m.group(1)
        continue
    m = re.match(r"([A-Z]\w*)\s*,?$", line)
    if m:
        rows.append((m.group(1), msg or ""))
        msg = None

out = ROOT / "packages/sdk/src/generated/errors.ts"
out.parent.mkdir(parents=True, exist_ok=True)
lines = [
    "// Generated by scripts/gen_sdk_errors.py from programs/pump-hooks/src/errors.rs. Do not edit.",
    "",
    "export const PROGRAM_ERRORS: readonly { code: number; name: string; msg: string }[] = [",
]
for i, (name, m) in enumerate(rows):
    lines.append(f"  {{ code: {6000 + i}, name: {json.dumps(name)}, msg: {json.dumps(m)} }},")
lines += ["] as const;", ""]
out.write_text("\n".join(lines))
print(f"wrote {out.relative_to(ROOT)} ({len(rows)} errors)")
